"""Third extraction route (issue #71): native-text-layer PDF -> Markdown,
same two-step pipeline as `pdf_text_generic.py` (issue #68) but with a
per-document filtering spec **generated by a Bedrock LLM**, instead of no
spec at all (generic-only) or a hand-written one (issue #59, the 10
`case-1-carolina-mmgd/` PDFs).

## What the LLM does and does not do

The LLM never rewrites, summarizes or reorders a single character of the
document. Its only output is a filtering *spec* — the same JSON shape
issue #59 wrote by hand under
`hackathon/tools/prototypes/pdf_to_markdown/specs/*.json` (`drop_pages`,
`drop_line_literals`, `drop_line_contains`, `strip_trailing_rubric_tokens`,
`notes`) — which `filter_verbatim.filter_lines`/`main()` (issue #59) then
applies exactly the same way it applies a hand-written spec: it only ever
*deletes* lines/pages that match a rule; everything else is copied through
byte for byte from `pdftotext -layout`'s own output. This is what keeps the
"cópia verbatim, nunca paráfrase" guarantee (D14) true *by construction*,
regardless of anything the LLM decides: a bug in the LLM's judgment can
cause it to under-remove (leave boilerplate in) or over-remove (drop a page
it shouldn't have) — both are visible, auditable mistakes in the spec JSON
— but it can never cause a paraphrase, because the only operation available
to the spec is deletion.

## Why an LLM call and not more hand-written regexes

`pdf_text_generic.py`'s built-in regexes (`filter_verbatim.LINE_DROP_PATTERNS`
etc.) already remove the boilerplate that repeats near-identically across
*every* document in the corpus (SICNET/SEI signature/certification
footers). What is left over — and what issue #59's hand-written specs show
— is genuinely *per-document*: a reviewer's rubric initials repeated on
every page, a company-specific letterhead/address footer, an ICP-Brasil
digital-signature stamp `pdftotext -layout` garbles differently depending
on the PDF's own column layout, or (rare, not seen in the 10 case-1 PDFs)
a whole embedded attachment. Writing one more generic regex per document
family does not scale to the corpus's ~2682 documents; an LLM reading the
same per-page raw text a human reviewer would read, and emitting the same
kind of spec, does.

## Model choice (acceptance criterion 1)

Both `us.anthropic.claude-haiku-4-5-20251001-v1:0` and `us.anthropic.claude-sonnet-5`
were confirmed to invoke successfully via Bedrock's `Converse` API in
`us-east-1` on this account (see the issue #71 evidence pack for the raw
probe output: model id, region, `usage.inputTokens`/`outputTokens`, no
credentials logged). Both were then piloted on the richest of the 10
case-1 PDFs (`recurso-48500.000639-2019-07.pdf`, the one issue #59's own
spec required all four spec fields for) with the exact prompt below,
side by side. Haiku 4.5's output was materially as good as Sonnet 5's —
same signature/footer/certificate lines identified, same conservative
`drop_pages: []` decision — at roughly 1/3 the per-document cost (Haiku
4.5: $1.00/$5.00 per MTok in/out; Sonnet 5: $2.00/$10.00 per MTok, Anthropic
published rates, used here as the Bedrock on-demand cost basis — see
`PRICING_USD_PER_MILLION_TOKENS` below and the evidence pack's cost table).
Per issue #71's own instruction ("preferir o mais barato que passe no
piloto"), **Haiku 4.5 is `DEFAULT_MODEL_ID`**; `PdfLlmSpecRoute` still takes
`model_id` as a constructor argument so a future run can swap in Sonnet 5
for a document family where Haiku's judgment turns out to be insufficient,
without touching this module's code.

## The prompt (auditable, not just "ask an LLM")

`SYSTEM_PROMPT` below is the full instruction sent on every call. Notable
design choices, all present because an earlier, looser version of this
prompt was piloted against the same richest case-1 PDF and produced a
worse spec (see the evidence pack for the side-by-side):

- It tells the model exactly which boilerplate the generic filter already
  removes, so the model does not waste output tokens (= cost) re-deriving
  rules that already exist, and does not risk double-specifying a rule in
  a way that conflicts with the generic one.
- `drop_pages` is deliberately the most restrictive field, with an explicit
  allow-list (a full "Relatório de Vistoria"/"Laudo Técnico", or a
  "Contrato Social") and an explicit warning **not** to treat the source
  system's own `(ANEXO: NNN)` corner-stamp label as a removal signal — that
  label is SICNET/SEI's generic word for "an attached file in this
  process", used for the Exposição de Motivos and Razões de Recurso just as
  much as for a genuine third-party letter (see
  `hackathon/tools/prototypes/pdf_to_markdown/README.md`, "Where the AC's
  line lives"). An early pilot without this warning had Sonnet 5 drop two
  genuinely-labelled-`(ANEXO: 001)` pages of `recurso-48500.000639-2019-07.pdf`
  that are a third-party letter reproduced as evidence, not a vistoria
  report/laudo técnico/contrato social — exactly the over-removal this
  warning exists to prevent.
- A dedicated paragraph tells the model that "identificação de quem
  assinou" also applies to a signature block *inside* correspondence kept
  as evidence (an embedded email/letter), not only to the document's own
  primary signer — because issue #59's manual spec for this same PDF
  removes exactly that (the two embedded correspondents' closing signature
  blocks on pages 24-26), while keeping the email routing headers and
  message bodies verbatim.
- `notes` is required even when every list is empty, forcing the model to
  state it actually reviewed the document rather than defaulting silently.

## Remaining, documented differences from the 10 manual specs (#59)

Piloting the final prompt above against all 10 case-1 PDFs (see the
evidence pack) found the LLM-generated specs produce Markdown that is
**line-for-line identical or a strict superset** of the manually-filtered
Markdown for 9 of the 10 documents (the LLM leaves a small number of extra
boilerplate/signature lines in place that the manual spec removed — never
the reverse; no case of the LLM removing real content the manual spec
kept). The one documented exception is
`recurso-48500.000639-2019-07.pdf`: both Haiku 4.5 and Sonnet 5, even with
the embedded-correspondence-signature paragraph above, chose *not* to
remove the two embedded correspondents' closing signature blocks (page 24's
garbled "Ronaldo de Oliveira" line and the letterhead/footer lines next to
it; pages 25-26's "Emerson da Silva Ribeiro"/"Ronaldo de Oliveira" email
closings) that the manual spec does remove — Sonnet 5's own `notes` explain
why: the page-24 text is visibly OCR-garbled (a known, documented
extraction-quality limitation, see the prototype README's "Known
limitation" section) and the model judged an exact-literal-match rule
against garbled text too risky to specify safely, preferring to leave a
few extra signature-identification lines in rather than risk a wrong match
against degraded text. This is a legitimate, explained difference in
judgment, not a defect: it makes the LLM route strictly more conservative
(never drops real content) at the cost of a handful of leftover
signature-identification lines on one page of one of the 10 documents.

## Two-tier cache: executor cache vs. this route's own spec cache

The executor's cache (`executor.py`, keyed by `(sha256, extractor_version)`)
decides whether `extract()` is called *at all* for a given document — a
cache hit there never reaches this module. `extractor_version` is a fixed
string per deployment of this route (bumped only when the *code* — prompt
text, filter logic, model default — changes in a way that would change
every document's output), so bumping it invalidates the whole corpus's
cache at once, which is correct for a code change but wrong for "I want to
regenerate just one document's LLM-generated spec".

That per-document regeneration is what this module's own spec cache is
for (acceptance criterion: "regerar uma spec invalida o cache só daquele
documento"). It is content-addressed, not version-addressed: the cache key
is `sha256(raw_pdftotext_output) + PROMPT_VERSION + model_id`
(`_spec_cache_key`), stored as one JSON file per document under
`<output_dir>/llm_specs/<key>.json` (a sibling of the executor's own
`markdown/`/`cache/` directories — derived from `out_path.parent.parent`,
since a route is never given `output_dir` directly per the extraction-route
contract). Regenerating one document's spec is: delete that one file (and,
so the executor actually calls `extract()` again, that document's own
executor cache entry, `<output_dir>/cache/<sha256>__<extractor_version>.json`
— also content-addressed by `sha256`, so removing it never touches any
other document). Both caches only ever key by content, never by a global
version counter that would force the whole corpus to redo LLM calls (and
re-spend money) for a change scoped to one document.
"""

