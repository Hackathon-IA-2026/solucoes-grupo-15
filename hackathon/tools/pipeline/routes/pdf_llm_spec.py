SYSTEM_PROMPT = """Você decide o que REMOVER do texto bruto de um PDF oficial da ANEEL, extraído mecanicamente por pdftotext -layout, página por página (marcadores "<!-- pdftotext:page N -->").

Você NUNCA reescreve, resume ou parafraseia nada. Sua única saída é uma especificação de remoção (JSON), aplicada por um programa determinístico que apenas deleta linhas/páginas que casam exatamente com o que você especificar — o resto do texto é copiado byte a byte, incluindo erros de OCR/layout.

Um filtro genérico JÁ remove automaticamente, em todo documento, sem você precisar listar:
- "Documento assinado digitalmente." e "Consulte a autenticidade deste documento em http://sicnet2.aneel.gov.br/...";
- "Documento assinado digitalmente por <nome>, em <data> às <hora>";
- "(Assinado digitalmente)"/"(Assinatura digital)" seguido do nome/cargo do signatário (até 3 linhas);
- o parágrafo SEI "Documento assinado eletronicamente por ..." + parágrafo de autenticidade + linha "Referência: Processo nº ...";
- o carimbo de número de processo/protocolo quando é a primeira linha não-vazia da página;
- o rodapé "<carimbo> SEI <processo> / pg. N" repetido em toda página;
- o rodapé antigo "Pág. N da Exposição de Motivos ...".

Sua tarefa é encontrar o que é ESPECÍFICO deste documento e ainda sobra, usando 5 campos:

1. drop_pages (MUITO RESTRITIVO — use raramente): páginas inteiras a descartar. Só se aplica quando a página é, ela mesma, um dos três tipos abaixo, com fronteira clara (cabeçalho/título próprio diferente do documento principal):
   (a) um "Relatório de Vistoria" ou "Laudo Técnico" completo (relatório de inspeção/engenharia, com seções técnicas próprias: objetivo, metodologia, constatações);
   (b) um "Contrato Social" (ato constitutivo de empresa, registrado em Junta Comercial);
   (c) nada além disso.
   NÃO use drop_pages para: cartas/ofícios/e-mails de terceiros citados como prova ou precedente (mesmo que sobre outro assunto ou processo, mesmo com outro signatário) — esses ficam; o rótulo do sistema "(ANEXO: NNN)" no canto da página NÃO é sinal de nada — é a numeração interna do SICNET/SEI para qualquer arquivo do processo, inclusive a própria Exposição de Motivos, Razões de Recurso, Votos e a correspondência citada como prova. Na dúvida, NÃO remova a página — prefira sempre manter o conteúdo e remover só a assinatura/rubrica com os outros 3 campos.

2. drop_line_literals: uma linha específica repetida neste documento (rubrica/iniciais de revisor, um carimbo de certificado digital ICP-Brasil garbled, uma linha de rodapé de endereço/telefone/e-mail institucional) — cópia EXATA (após strip) da linha.

3. drop_line_contains: um SUBSTRING de uma linha garbled (carimbo de assinatura digital multi-coluna que o pdftotext espalha/mistura com o texto ao redor, com espaçamento irregular entre letras) — só quando não dá para casar a linha inteira por drop_line_literals.

4. strip_trailing_rubric_tokens: um token curto (iniciais) que aparece sempre no FINAL de uma linha de conteúdo real (ex.: endereço) e deve ser removido do final da linha, mantendo o resto da linha.

5. notes (obrigatório): texto justificando CADA regra proposta — por que existe, o que remove, por que não é conteúdo principal. Se as 4 listas vierem vazias, diga isso explicitamente e confirme que revisou o documento e não achou nada específico além do filtro genérico.

Nunca remova: rótulos de formulário (ex. "NOME:", "CARGO/FUNÇÃO:", "ASSINATURA:"), corpo de e-mails/cartas reproduzidos como prova ou precedente, ou qualquer conteúdo argumentativo/legal/técnico — só identificação de quem assinou, rubricas de revisor, carimbos de certificado digital, e (raramente) anexos completos do tipo (a)/(b) acima.

IMPORTANTE — assinaturas dentro de correspondência reproduzida como prova: quando uma página reproduz uma carta ou e-mail de terceiros como prova/precedente (algo que você decidiu manter, não é um anexo do tipo (a)/(b)), a regra de "identificação de quem assinou" AINDA se aplica ao encerramento dessa carta/e-mail — mantenha o corpo da mensagem (texto, datas, valores, argumentos) e os cabeçalhos de roteamento de e-mail (De/Para/Cc/Assunto/Enviado em) INTEGRALMENTE, mas remova o bloco de assinatura de encerramento de quem escreveu (nome completo, cargo, departamento, empresa, telefone, e-mail pessoal, site) — trate como identificação de quem assinou, mesmo não sendo o signatário principal do documento. Se o texto dessa assinatura estiver visivelmente degradado/garbled pelo OCR/layout a ponto de um casamento literal ser arriscado, é aceitável deixá-la — documente essa decisão em notes.
"""


@dataclass
class SpecGenerationResult:
    spec: dict
    model_id: str
    region: str
    input_tokens: int
    output_tokens: int


class SpecGenerationError(Exception):
    """Raised when the LLM call fails or returns a spec that fails
    validation — the route's caller decides the fallback (see
    `PdfLlmSpecRoute.extract`)."""


class GenerateFn(Protocol):
    def __call__(self, raw_text: str) -> SpecGenerationResult: ...


def estimate_cost_usd(model_id: str, input_tokens: int, output_tokens: int) -> float | None:
    pricing = PRICING_USD_PER_MILLION_TOKENS.get(model_id)
    if pricing is None:
        return None
    return (input_tokens * pricing["input"] + output_tokens * pricing["output"]) / 1_000_000


def _validate_spec(spec: dict) -> dict:
    """Defensive validation of the LLM's tool-call input — never trust it
    blindly. Raises `SpecGenerationError` on any shape mismatch; the caller
    falls back to the generic-only filter rather than applying a malformed
    spec."""
    if not isinstance(spec, dict):
        raise SpecGenerationError(f"spec não é um objeto JSON: {spec!r}")

    def _list_of_str(key: str) -> list[str]:
        value = spec.get(key, [])
        if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
            raise SpecGenerationError(f"campo {key!r} não é uma lista de strings: {value!r}")
        return value

    drop_pages = spec.get("drop_pages", [])
    if not isinstance(drop_pages, list) or not all(isinstance(item, int) for item in drop_pages):
        raise SpecGenerationError(f"campo drop_pages não é uma lista de inteiros: {drop_pages!r}")

    notes = spec.get("notes")
    if not isinstance(notes, str) or not notes.strip():
        raise SpecGenerationError(f"campo notes ausente ou vazio: {notes!r}")

    return {
        "drop_pages": drop_pages,
        "drop_line_literals": _list_of_str("drop_line_literals"),
        "drop_line_contains": _list_of_str("drop_line_contains"),
        "strip_trailing_rubric_tokens": _list_of_str("strip_trailing_rubric_tokens"),
        "notes": notes,
    }


def make_bedrock_generate_fn(model_id: str = DEFAULT_MODEL_ID, region: str = REGION) -> GenerateFn:
    """Builds a `GenerateFn` backed by a real Bedrock `Converse` call —
    the production path. Tests inject their own fake `GenerateFn` instead
    (see `test_routes_pdf_llm_spec.py`) so they never depend on real
    credentials or spend real money."""
    import boto3

    client = boto3.client("bedrock-runtime", region_name=region)

    def generate(raw_text: str) -> SpecGenerationResult:
        line_count = raw_text.count("\n")
        response = client.converse(
            modelId=model_id,
            system=[{"text": SYSTEM_PROMPT}],
            messages=[
                {
                    "role": "user",
                    "content": [
                        {"text": f"Texto bruto (pdftotext -layout, {line_count} linhas):\n\n{raw_text}"}
                    ],
                }
            ],
            toolConfig={
                "tools": [SPEC_TOOL_SCHEMA],
                "toolChoice": {"tool": {"name": SPEC_TOOL_NAME}},
            },
            inferenceConfig={"maxTokens": 4096},
        )
        usage = response["usage"]
        tool_input = None
        for block in response["output"]["message"]["content"]:
            if "toolUse" in block:
                tool_input = block["toolUse"]["input"]
                break
        if tool_input is None:
            raise SpecGenerationError(
                f"resposta do Bedrock não contém toolUse (stopReason={response.get('stopReason')!r})"
            )
        spec = _validate_spec(tool_input)
        return SpecGenerationResult(
            spec=spec,
            model_id=model_id,
            region=region,
            input_tokens=usage["inputTokens"],
            output_tokens=usage["outputTokens"],
        )

    return generate


def _spec_cache_key(raw_text: str, model_id: str) -> str:
    digest = hashlib.sha256()
    digest.update(raw_text.encode("utf-8"))
    digest.update(b"|")
    digest.update(PROMPT_VERSION.encode("utf-8"))
    digest.update(b"|")
    digest.update(model_id.encode("utf-8"))
    return digest.hexdigest()


class PdfLlmSpecRoute:
    """See module docstring for the full design rationale. Registered
    *before* `PdfTextGenericRoute` in `cli.py::build_registry()` — both
    claim `formato == "pdf"`, and `RouteRegistry.dispatch` picks the first
    match, so this route is the one every PDF actually reaches; the
    fallback to generic-only filtering happens *inside* `extract()`
    (below), never by falling through to a second registered route."""

    name = "pdf_llm_spec"
    extractor_version = EXTRACTOR_VERSION

    def __init__(
        self,
        model_id: str = DEFAULT_MODEL_ID,
        region: str = REGION,
        generate_fn: GenerateFn | None = None,
        spec_cache_dir: Path | None = None,
    ):
        self.model_id = model_id
        self.region = region
        self._generate_fn = generate_fn
        self._spec_cache_dir_override = spec_cache_dir

    def can_handle(self, formato: str | None) -> bool:
        return formato == "pdf"

    def extract(self, source_path: Path, out_path: Path) -> ExtractionResult:
        try:
            page_count = _extract_raw_text.count_pages(source_path)
        except Exception as exc:
            return ExtractionResult(
                status="error",
                extractor_version=self.extractor_version,
                route=self.name,
                message=f"pdfinfo falhou: {exc}",
            )

        if page_count == 0:
            return ExtractionResult(
                status="error",
                extractor_version=self.extractor_version,
                route=self.name,
                message="pdfinfo reportou 0 páginas",
            )

        pages_text: list[str] = []
        for page in range(1, page_count + 1):
            try:
                pages_text.append(_extract_raw_text.extract_page(source_path, page))
            except Exception as exc:
                return ExtractionResult(
                    status="error",
                    extractor_version=self.extractor_version,
                    route=self.name,
                    message=f"pdftotext falhou na página {page}: {exc}",
                )

        total_chars = sum(len(re.sub(r"\s", "", text)) for text in pages_text)
        if total_chars / page_count < MIN_CHARS_PER_PAGE:
            # No usable text layer — not an LLM-spec question at all, same
            # heuristic and same fallback destination as pdf_text_generic.py.
            return ExtractionResult(
                status="pending",
                extractor_version=self.extractor_version,
                route=self.name,
                pages_total=page_count,
                message=(
                    "sem camada de texto extraível (media de "
                    f"{total_chars / page_count:.1f} caracteres/página) — "
                    "candidato à rota de OCR (#72)"
                ),
            )

        raw_lines: list[str] = []
        for page_no, text in enumerate(pages_text, start=1):
            raw_lines.append(f"<!-- pdftotext:page {page_no} -->")
            raw_lines.extend(text.split("\n"))
        raw_text = "\n".join(raw_lines)

        spec, spec_message = self._get_or_generate_spec(raw_text, out_path)

        drop_pages = set(spec.get("drop_pages", []))
        drop_line_literals = frozenset(spec.get("drop_line_literals", []))
        drop_line_contains = tuple(spec.get("drop_line_contains", []))
        strip_trailing_rubric_tokens = tuple(spec.get("strip_trailing_rubric_tokens", []))

        pages = _filter_verbatim.split_pages(raw_text)
        kept_lines: list[str] = []
        raw_line_count = 0
        pages_dropped_whole = 0
        for page_no, page_lines in pages:
            raw_line_count += len(page_lines)
            if page_no in drop_pages:
                pages_dropped_whole += 1
                continue
            kept_lines.append(f"<!-- page:{page_no} -->")
            page_lines = _filter_verbatim.drop_first_line_protocol_stamp(page_lines)
            kept_lines.extend(
                _filter_verbatim.filter_lines(
                    page_lines, drop_line_literals, drop_line_contains, strip_trailing_rubric_tokens
                )
            )
            kept_lines.append("")
        kept_lines = _filter_verbatim.collapse_blank_runs(kept_lines)

        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text("\n".join(kept_lines).rstrip() + "\n", encoding="utf-8")

        kept_line_count = sum(1 for line in kept_lines if line.strip())
        percent_removed = (
            100.0 * (1 - kept_line_count / raw_line_count) if raw_line_count else 0.0
        )

        pages_kept = len(pages) - pages_dropped_whole
        message = spec_message
        if pages_dropped_whole:
            drop_note = f"{pages_dropped_whole} página(s) descartada(s) inteira(s) (anexo/contrato social)"
            message = f"{message}; {drop_note}" if message else drop_note

        return ExtractionResult(
            status="extracted",
            extractor_version=self.extractor_version,
            route=self.name,
            markdown_path=out_path,
            pages_total=page_count,
            pages_kept=pages_kept,
            percent_removed=round(percent_removed, 1),
            message=message,
        )

    def _spec_cache_dir(self, out_path: Path) -> Path:
        if self._spec_cache_dir_override is not None:
            return self._spec_cache_dir_override
        # `out_path` is `<output_dir>/markdown/<sha256>__<extractor_version>.md`
        # (see executor.py's `_extract`) — a route is never handed
        # `output_dir` directly per the extraction-route contract, so this
        # derives the sibling `llm_specs/` directory from the one path
        # this method does receive. See module docstring, "Two-tier cache".
        return out_path.parent.parent / "llm_specs"

    def _get_or_generate_spec(self, raw_text: str, out_path: Path) -> tuple[dict, str | None]:
        cache_dir = self._spec_cache_dir(out_path)
        cache_key = _spec_cache_key(raw_text, self.model_id)
        cache_path = cache_dir / f"{cache_key}.json"

        if cache_path.exists():
            cached = json.loads(cache_path.read_text(encoding="utf-8"))
            return cached["spec"], f"spec LLM em cache ({cached['model_id']})"

        generate_fn = self._generate_fn or make_bedrock_generate_fn(self.model_id, self.region)
        try:
            result = generate_fn(raw_text)
            result.spec = _validate_spec(result.spec)  # never trust a GenerateFn blindly,
            # whether it's the real Bedrock-backed one or a test double —
            # see _validate_spec's own docstring.
        except Exception as exc:
            # LLM call failed or returned something we can't trust (see
            # SpecGenerationError/_validate_spec) — fall back to the
            # generic-only filter (no per-document spec) rather than
            # erroring the whole document out. This is this route's own
            # documented precedence decision between "use the LLM spec"
            # and "behave like pdf_text_generic.py" (see module docstring).
            empty_spec = {
                "drop_pages": [],
                "drop_line_literals": [],
                "drop_line_contains": [],
                "strip_trailing_rubric_tokens": [],
                "notes": "",
            }
            return empty_spec, f"geração de spec via LLM falhou, usando filtro genérico: {exc}"

        cost_usd = estimate_cost_usd(result.model_id, result.input_tokens, result.output_tokens)
        cache_dir.mkdir(parents=True, exist_ok=True)
        cache_path.write_text(
            json.dumps(
                {
                    "spec": result.spec,
                    "model_id": result.model_id,
                    "region": result.region,
                    "prompt_version": PROMPT_VERSION,
                    "input_tokens": result.input_tokens,
                    "output_tokens": result.output_tokens,
                    "cost_usd": cost_usd,
                    "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                },
                ensure_ascii=False,
                indent=2,
            ),
            encoding="utf-8",
        )
        message = (
            f"spec gerada via LLM ({result.model_id}, "
            f"{result.input_tokens}+{result.output_tokens} tokens"
            + (f", ~US${cost_usd:.4f}" if cost_usd is not None else "")
            + ")"
        )
        return result.spec, message
